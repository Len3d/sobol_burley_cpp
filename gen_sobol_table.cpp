// Generator for `sobol_4096spp_256d.h`.
//
// Emits the first 4096 samples x 256 dimensions of the seedable
// Owen-scrambled Sobol sequence (seed = 0), stored as 32-bit integers in
// normal bit order.  To recover the value in [0, 1), divide by 2^32:
//
//     float v01 = sobol_sequence[i][d] / 4294967296.0f;
//
// This is exactly the integer underlying sobol_burley::sample(i, d, 0), so it
// matches the library's float output to within the library's own 23-bit
// precision (error < 1.2e-7).

#include "sobol_burley.hpp"

#include <cstdio>

using namespace sobol_burley;

namespace {

// The integer underlying sample(i, d, 0), before the [0,1) float conversion.
inline uint32_t sample_int(uint32_t sample_index, uint32_t dimension) {
    constexpr uint32_t kSeed = 0u;

    const uint32_t shuffled_rev_index =
        owen_scramble_rev(reverse_bits(sample_index), hash(kSeed ^ 0x79c68e4au));

    const uint32_t sobol = sobol_rev(shuffled_rev_index, dimension);

    static constexpr std::array<uint32_t, 4> kScrambleConsts = {
        0x912f69bau, 0x174f18abu, 0x691e72cau, 0xb40cc1b8u};
    const uint32_t seed_ = kSeed * 0x9c8f2d3bu;
    const uint32_t ds = dimension >> 2;
    const uint32_t scramble = ds ^ seed_ ^ kScrambleConsts[dimension & 0b11u];

    const uint32_t sobol_owen_rev = owen_scramble_rev(sobol, hash(scramble));

    return reverse_bits(sobol_owen_rev);
}

}  // namespace

int main(int argc, char** argv) {
    constexpr uint32_t kSamples = 4096;
    constexpr uint32_t kDims = 256;

    const char* out_path =
        (argc > 1) ? argv[1] : "sobol_4096spp_256d.h";

    FILE* f = fopen(out_path, "wb");
    if (!f) {
        std::fprintf(stderr, "error: cannot open %s for writing\n", out_path);
        return 1;
    }

    std::fprintf(f,
                 "#pragma once\n"
                 "\n"
                 "// Auto-generated by gen_sobol_table. Do not edit.\n"
                 "//\n"
                 "// First %u samples x %u dimensions of the Owen-scrambled Sobol\n"
                 "// sequence (sobol_burley, seed = 0). Values are 32-bit integers in\n"
                 "// normal bit order; convert to [0,1) with: v / 4294967296.0f\n"
                 "static const uint32_t sobol_sequence[%u][%u] = {\n",
                 kSamples, kDims, kSamples, kDims);

    for (uint32_t i = 0; i < kSamples; ++i) {
        std::fprintf(f, "  {\n");
        for (uint32_t d = 0; d < kDims; ++d) {
            if (d % 8 == 0) std::fprintf(f, "    ");
            std::fprintf(f, "0x%08x%s", sample_int(i, d),
                         (d == kDims - 1) ? "" : ",");
            if (d % 8 == 7 || d == kDims - 1) std::fprintf(f, "\n");
        }
        std::fprintf(f, "  },\n");
    }
    std::fprintf(f, "};\n");

    std::fclose(f);
    std::printf("Wrote %u x %u table to %s\n", kSamples, kDims, out_path);
    return 0;
}
